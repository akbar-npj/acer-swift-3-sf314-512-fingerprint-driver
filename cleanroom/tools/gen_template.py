#!/usr/bin/env python3
"""Generate cleanroom/src/fpc_bep_template.c from a BEPSNAP1 capture.

The snapshot records the whole pointer graph handed to cr_bep_process_1c810.
Only the small control structures carry information; every large buffer is
scratch that the BEP fills itself.  This tool keeps the structures, drops the
scratch, copies any static objects that live inside the vendor image, and
emits a C table with the pointer fix-ups resolved by block index.

Usage: gen_template.py <snapshot> <out.c>
"""
import struct
import sys

MAGIC = b"BEPSNAP1"
KEEP = 0x8000          # blocks >= this are scratch
IMG_COPY = 0x800       # bytes copied for a static object inside the image

# Static objects referenced through g_cr_image_base by the BEP path.
IMG_ROOTS = {
    0x16f4c8: 0x40,     # cr_bio context head
    0x117800: 0x6400,   # calibration blob 5 (0x1900 floats)
    0x12d3a0: 0x4000,   # calibration blob 6 (0x1000 floats)
    0x159ea0: 0x400,    # descriptor chains
    0x122980: 0x400,
    0x1598e0: 0x400,
    0x1229e0: 0x400,
    0xa0c80:  0x400,
}


def load(path):
    d = open(path, "rb").read()
    if d[:8] != MAGIC:
        raise SystemExit("bad magic")
    off = 8
    n, imgsz = struct.unpack_from("<II", d, off)
    off += 8
    base = struct.unpack_from("<Q", d, off)[0]
    off += 8
    roots = struct.unpack_from("<5Q", d, off)
    off += 40
    a6 = struct.unpack_from("<q", d, off)[0]
    off += 8
    image = d[off:off + imgsz]
    off += imgsz
    blocks = []
    for _ in range(n):
        addr, size, pad = struct.unpack_from("<QII", d, off)
        off += 16
        data = d[off:off + size]
        off += size
        blocks.append([addr, size, bytearray(data)])
    return roots, a6, image, blocks


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    roots, a6, image, blocks = load(sys.argv[1])
    by_addr = {b[0]: i for i, b in enumerate(blocks)}

    entries = []
    for i, (addr, size, data) in enumerate(blocks):
        entries.append({"idx": i, "size": size, "stored": size < KEEP,
                        "data": data, "addr": addr})

    def add_image_block(v):
        """Copy a static object out of the vendor image into the template."""
        rva = v - 0x180000000
        if not 0 <= rva < len(image):
            raise SystemExit("pointer %#x outside the image" % v)
        n = min(IMG_COPY, len(image) - rva)
        idx = len(entries)
        entries.append({"idx": idx, "size": n, "stored": True,
                        "data": bytearray(image[rva:rva + n]), "addr": v})
        by_addr[v] = idx
        return idx

    # Resolve pointers, synthesising blocks for image objects as needed.
    changed = True
    while changed:
        changed = False
        for e in entries:
            if not e["stored"]:
                continue
            for off in range(0, e["size"] - 7, 8):
                v = struct.unpack_from("<Q", e["data"], off)[0]
                if 0x10000 <= v < 0x800000000000 and v not in by_addr:
                    if 0x180000000 <= v < 0x180180000:
                        add_image_block(v)
                        changed = True

    fixups = []
    for e in entries:
        if not e["stored"]:
            continue
        for off in range(0, e["size"] - 7, 8):
            v = struct.unpack_from("<Q", e["data"], off)[0]
            if v in by_addr:
                fixups.append((e["idx"], off, by_addr[v]))

    out = []
    out.append("/* Generated by gen_template.py from %s -- do not edit. */\n"
               % sys.argv[1])
    out.append("#include \"fpc_bep_template.h\"\n\n")

    # Transitive closure of the static objects reached through the image base.
    regions = {}
    todo = [(rva, sz) for rva, sz in IMG_ROOTS.items()]
    while todo:
        rva, size = todo.pop()
        if rva in regions:
            continue
        size = min(size, len(image) - rva)
        regions[rva] = bytes(image[rva:rva + size])
        for off in range(0, size - 7, 8):
            v = struct.unpack_from("<Q", image, rva + off)[0]
            if 0x180000000 <= v < 0x180180000 and (v - 0x180000000) not in regions:
                todo.append((v - 0x180000000, 0x400))

    for k, (rva, data) in enumerate(sorted(regions.items())):
        out.append("static const uint8_t st%d[%d] = {" % (k, len(data)))
        for j, byte in enumerate(data):
            if j % 16 == 0:
                out.append("\n    ")
            out.append("%d," % byte)
        out.append("\n};\n\n")

    out.append("const cr_bep_region cr_bep_static[] = {\n")
    for k, (rva, data) in enumerate(sorted(regions.items())):
        out.append("    { %d, %d, st%d },\n" % (rva, len(data), k))
    out.append("};\n")
    out.append("const int cr_bep_static_count = %d;\n"
               % len(regions))
    out.append("const uint32_t cr_bep_image_size = %d;\n" % len(image))

    for e in entries:
        if not e["stored"]:
            continue
        out.append("static const uint8_t blk%d[%d] = {" % (e["idx"], e["size"]))
        for k, byte in enumerate(e["data"]):
            if k % 16 == 0:
                out.append("\n    ")
            out.append("%d," % byte)
        out.append("\n};\n\n")

    for e in entries:
        ptrs = [f for f in fixups if f[0] == e["idx"]]
        if ptrs:
            out.append("static const cr_bep_ptr ptr%d[] = {" % e["idx"])
            out.append(", ".join("{ %d, %d }" % (off, tgt)
                                 for _, off, tgt in ptrs))
            out.append("};\n\n")

    out.append("const cr_bep_blk cr_bep_template[] = {\n")
    for e in entries:
        nptr = len([f for f in fixups if f[0] == e["idx"]])
        data = "blk%d" % e["idx"] if e["stored"] else "0"
        ptr = "ptr%d" % e["idx"] if nptr else "0"
        out.append("    { %d, %s, %d, %s },  /* block %d */\n"
                   % (e["size"], data, nptr, ptr, e["idx"]))
    out.append("};\n\n")
    out.append("const int cr_bep_template_count = %d;\n" % len(entries))
    out.append("const int cr_bep_template_a1 = %d;\n" % by_addr[roots[0]])
    out.append("const int cr_bep_template_a2 = %d;\n" % by_addr[roots[1]])
    out.append("const int cr_bep_template_a3 = %d;\n" % by_addr[roots[2]])
    out.append("const int cr_bep_template_a4 = %d;\n" % by_addr[roots[3]])
    out.append("const int cr_bep_template_a5 = %d;\n" % by_addr[roots[4]])
    out.append("const int cr_bep_template_a6 = %d;\n" % a6)

    a4 = blocks[by_addr[roots[3]]][2]
    pixbuf = struct.unpack_from("<Q", a4, 0)[0]
    frame = struct.unpack_from("<Q", blocks[by_addr[pixbuf]][2], 0x10)[0]
    meta = struct.unpack_from("<Q", a4, 0x38)[0]
    out.append("const int cr_bep_template_frame = %d;\n" % by_addr[frame])
    out.append("const int cr_bep_template_meta = %d;\n" % by_addr[meta])

    open(sys.argv[2], "w").write("".join(out))
    print("wrote %s (%d blocks, %d fix-ups)" % (sys.argv[2], len(entries),
                                                len(fixups)))


if __name__ == "__main__":
    main()
